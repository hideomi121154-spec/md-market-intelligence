/* No external services required.  */
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const ctx={window:{},URL,console};
vm.runInNewContext(fs.readFileSync(__dirname+'/storage.js','utf8'),ctx);
const s=ctx.window.MDStore;
const header='date,make,model,grade,year,mileage_km,price_jpy,channel,market_type,source_url,source_name\n';
const newRow='2026-10-29,ホンダ,N-BOX,L,2023,23000,1100000,auction,consumer_auction,https://www.sellca-sellcar.com/trade_result/,SellCa\n';
const parsed=s.readRecords(header+newRow);
assert.equal(parsed.records.length,1);
const row={...parsed.records[0],id:'original-source-and-value-identifier'};
assert.equal(row.evidence_status,'unverified','imported data cannot claim external verification');
assert.equal(s.eligibleForManualCheck(row),true);
assert.throws(()=>s.validateReviewInput(row,'user_checked','原本確認しました',false),/確認/);
assert.throws(()=>s.validateReviewInput(row,'user_checked','短い',true),/10文字/);
const approved=s.validateReviewInput(row,'user_checked','原本URLの成約日、価格、車両条件、市場区分を確認',true);
assert.equal(approved.status,'user_checked');
assert.equal(approved.id,row.id);
assert.match(approved.checked_at,/^\d{4}-\d\d-\d\dT/);
assert.match(approved.notes,/市場区分/);
const flagged=s.validateReviewInput(row,'flagged','元ページが削除されている',false);
assert.equal(flagged.status,'flagged');
assert.throws(()=>s.validateReviewInput(row,'flagged','NG',false),/5文字/);
assert.equal(s.validateReviewInput(row,'unverified','',false).status,'unverified');
assert.equal(s.eligibleForManualCheck({...row,market_type:'unspecified_auction'}),false);
assert.equal(s.eligibleForManualCheck({...row,source_url:'https://example.test/car'}),false);
assert.equal(s.eligibleForManualCheck({...row,source_url:'https://example.com/car'}),false);
assert.equal(s.eligibleForManualCheck({...row,source_url:'javascript:alert(1)'}),false);
assert.equal(s.eligibleForManualCheck({...row,source_url:'https://public-example.co.jp/verified-report'}),true);
const retail=s.readRecords(header.replace('auction','auction')+'2026-10-29,トヨタ,アクア,G,2022,24000,1490000,retail,retail_listing,https://example-shop.co.jp/item,Shop\n');
assert.equal(retail.records.length,1);
assert.equal(retail.records[0].market_type,'retail_listing');
const sample=s.summarize([parsed.records[0],retail.records[0]]);
assert.equal(sample.mixed,true);
assert.equal(sample.median_price_jpy,null);
console.log('PASS: original value imports unverified, source/market gate, human confirmation, notes, audit metadata and retail/auction separation');
