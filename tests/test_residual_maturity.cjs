'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const api=require('../residual-maturity.js');
const reg=JSON.parse(fs.readFileSync(path.join(root,'data/registered_annual_history.json'),'utf8'));
const kei=JSON.parse(fs.readFileSync(path.join(root,'data/kei_annual_history.json'),'utf8'));
const registered=api.validateDataset(reg,'registered');
const light=api.validateDataset(kei,'kei');
assert.equal(registered.length,5);assert.equal(light.length,5);
const note=api.models(registered,'日産').find(m=>m.model==='ノート');
const days=api.models(light,'日産').find(m=>m.model==='デイズ');
assert.ok(note);assert.ok(days);
assert.equal(api.annualCohort(registered,2021,'日産',note.id).units,90177);
assert.equal(api.annualCohort(light,2021,'日産',days.id).units,53773);
assert.equal(api.annualCohort(registered,2020,'日産',note.id).units,null);
const assumptions={penetration:40,term3:20,term5:60,term7:20,returnRate:60,auctionShare:70};
const result=api.forecast(registered,'日産',note.id,assumptions);
const y2028=result.rows.find(x=>x.year===2028);
assert.equal(y2028.complete,true);assert.equal(y2028.missing.length,0);
assert.equal(y2028.secondary,true,'2021 secondary cannot be promoted to primary');
const matured=78123*.4*.2+102508*.4*.6+90177*.4*.2;
assert.ok(Math.abs(y2028.matured-matured)<1e-8);
assert.ok(Math.abs(y2028.returned-matured*.6)<1e-8);
assert.ok(Math.abs(y2028.aa-matured*.6*.7)<1e-8);
assert.equal(y2028.cohorts.find(c=>c.term===7).sourceType,'secondary');
assert.equal(y2028.cohorts.find(c=>c.term===3).year,2025);
const y2031=result.rows.find(x=>x.year===2031);
assert.equal(y2031.complete,false);
assert.ok(y2031.missing.some(v=>v.includes('収録期間外')));
const ranked=api.forecast(registered,'日産','__RANKED_MAKE__',assumptions);
assert.equal(ranked.rows.find(x=>x.year===2028).partial,true);
assert.equal(ranked.rows.find(x=>x.year===2028).complete,false,'maker ranking is not full market');
const k=api.forecast(light,'日産',days.id,assumptions);
assert.equal(k.rows.find(x=>x.year===2028).complete,true);
assert.equal(k.rows.find(x=>x.year===2028).secondary,false);
const missing=JSON.parse(JSON.stringify(reg));
missing.years[2].models=missing.years[2].models.filter(x=>x.model!=='ノート');
assert.throws(()=>api.validateDataset(missing,'registered'));
const different=JSON.parse(JSON.stringify(reg));
different.years[0].source_type='official';
assert.throws(()=>api.validateDataset(different,'registered'));
assert.throws(()=>api.forecast(registered,'日産',note.id,{...assumptions,term7:19}),/100/);
assert.throws(()=>api.forecast(registered,'日産',note.id,{...assumptions,returnRate:''}),/返却率/);
assert.throws(()=>api.forecast(registered,'日産',note.id,{...assumptions,penetration:-1}),/0〜100/);
assert.throws(()=>api.forecast(registered,'日産','不存在',assumptions),/車種/);
const html=fs.readFileSync(path.join(root,'index.html'),'utf8'),sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
for(const asset of ['residual-maturity.js?v=3.2.0','residual-maturity.css?v=3.2.0']){
 assert.ok(html.includes(asset),'missing HTML asset '+asset);
 assert.ok(sw.includes(asset),'missing PWA asset '+asset);
}
assert.ok(html.includes('id="rm-panel"')&&html.includes('id="rm-results"')&&html.includes('id="rm-class"'));
assert.ok(html.indexOf('offline-data.js?v=2.0.3')<html.indexOf('residual-maturity.js?v=3.2.0'));
assert.ok(sw.includes("'./data/registered_annual_history.json'")&&sw.includes("'./data/kei_annual_history.json'"));
assert.ok(sw.includes('md-market-pwa-v3-3-0-20261101'));
console.log('PASS: cohort schedule, weighted scenarios, source labels, ranking gaps, PWA assets');
