'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const {evaluate,normalize,storageKey}=require('../residual-gap.js');
const c=(patch={})=>({residual:150,auction:160,expenses:15,residualTax:'tax_in',auctionTax:'tax_in',...patch});
const a=evaluate(c());
assert.equal(a.valid,true);
assert.equal(a.trade,145);
assert.equal(a.gap,-5);
assert.ok(Math.abs(a.gapPct+100/30)<1e-9);
assert.ok(Math.abs(a.rawGapPct-100/15)<1e-9);
assert.equal(a.auctionBreakEven,165);
assert.equal(a.signal,'return_advantage');
assert.equal(evaluate(c({auction:165})).signal,'even');
assert.equal(evaluate(c({auction:190})).signal,'trade_advantage');
assert.equal(evaluate(c({residualTax:'tax_out'})).valid,false,'reject mixed taxes');
assert.equal(evaluate(c({expenses:161})).valid,false);
assert.equal(evaluate(c({expenses:''})).valid,false,'missing deduction cannot be zero');
assert.equal(evaluate(c({auction:''})).valid,false);
assert.equal(evaluate(c({residual:0})).valid,false);
assert.equal(evaluate(c({residual:'NaN'})).valid,false);
assert.equal(evaluate(c({expenses:0})).trade,160);
const scenario=normalize({...c(),id:'x1',make:'日産',model:'ノート',grade:'E12',modelYear:'2022',sourceType:'scenario',sourceUrl:'',observedAt:'',note:'架空',createdAt:'2026-11-01T00:00:00Z'});
assert.equal(scenario.sourceType,'scenario');
assert.equal(scenario.make,'日産');
assert.throws(()=>normalize({...scenario,id:'invalid',sourceType:'checked'}));
assert.throws(()=>normalize({...scenario,id:'invalid',sourceUrl:'javascript:alert(1)'}));
assert.equal(normalize({...scenario,id:'verified',sourceType:'checked',sourceUrl:'https://example.org/aa',observedAt:'2026-11-01'}).sourceType,'checked');
assert.equal(storageKey,'md-market-residual-auction-gap-v1');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8'),sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
for(const asset of ['residual-gap.js?v=3.1.0','residual-gap.css?v=3.1.0']){assert.ok(html.includes(asset));assert.ok(sw.includes(asset));}
for(const id of ['rr-panel','rr-residual','rr-auction','rr-expenses','rr-sourceType','rr-out','rr-history','rr-export','rr-import','rr-backup'])assert.ok(html.includes('id="'+id+'"'),'missing '+id);
assert.ok(html.indexOf('<section class="screen" id="overview">')<html.indexOf('id="rr-panel"'));
assert.ok(html.indexOf('id="rr-panel"')<html.indexOf('<section class="screen" id="records">'));
assert.ok(sw.includes("md-market-pwa-v3-5-0-20261101"));
console.log('PASS: residual/AA calculation, tax/source validation, PWA assets');
