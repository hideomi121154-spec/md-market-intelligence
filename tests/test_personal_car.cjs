'use strict';
const assert=require('node:assert/strict');
const P=require('../personal-car.js');
const c={id:'car-1',make:'日産',model:'デイズ',grade:'X',year:2021,mileage:43000,color:'白',repair:'none'};
const t={id:'quote-1',car_id:'car-1',type:'estimate',source:'ガリバーの相場表示',source_url:'https://221616.com/satei/souba/',date:'2026-10-31',price:700000,notes:'手元で確認'};
const data=P.validate({cars:[c],quotes:[t]});
assert.equal(data.cars.length,1);
assert.equal(data.quotes.length,1);
assert.equal(P.summarize(data,'car-1').types.estimate.max,700000);
const next=P.merge(data,{cars:[c],quotes:[{...t,id:'quote-2',price:680000}]});
assert.equal(next.quotes.length,2);
assert.equal(P.summarize(next,'car-1').types.estimate.median,690000);
assert.equal(P.summarize(next,'car-1').types.offer.count,0);
const real={...t,id:'quote-3',type:'offer',price:810000,source:'地域の買取店',source_url:''};
const retail={...t,id:'quote-4',type:'retail',price:1200000,source:'小売掲載'};
const combined=P.merge(next,{cars:[c],quotes:[real,retail]});
assert.equal(P.summarize(combined,'car-1').types.offer.max,810000);
assert.equal(P.summarize(combined,'car-1').types.retail.max,1200000);
assert.equal(P.summarize(combined,'car-1').types.estimate.max,700000,'retail and offers must not mix with estimated prices');
assert.equal(P.merge(combined,combined).quotes.length,combined.quotes.length,'same backup is idempotent');
assert.deepEqual(P.restore(P.backup(combined)),combined);
assert.throws(()=>P.restore(JSON.stringify({schema_version:1,kind:'other',cars:[],quotes:[]})),/バックアップ/);
assert.throws(()=>P.restore('not JSON'),/JSON/);
assert.throws(()=>P.merge(combined,{cars:[{...c,mileage:55000}],quotes:[]}),/上書き/);
assert.throws(()=>P.merge(combined,{cars:[c],quotes:[{...real,price:999999}]}),/上書き/);
assert.throws(()=>P.validate({cars:[],quotes:[t]}),/車両情報/);
assert.throws(()=>P.validate({cars:[c,c],quotes:[]}),/重複/);
assert.throws(()=>P.validate({cars:[c],quotes:[t,t]}),/重複/);
assert.throws(()=>P.validate({cars:Array(51).fill(c),quotes:[]}),/上限/);
assert.throws(()=>P.validate({cars:[{...c,year:0}],quotes:[]}),/年式/);
assert.throws(()=>P.validate({cars:[{...c,mileage:-1}],quotes:[]}),/走行距離/);
assert.throws(()=>P.validate({cars:[{...c,repair:'invalid'}],quotes:[]}),/修復歴/);
assert.throws(()=>P.validate({cars:[c],quotes:[{...t,type:'auction'}]}),/価格区分/);
assert.throws(()=>P.validate({cars:[c],quotes:[{...t,price:NaN}]}),/金額/);
assert.throws(()=>P.validate({cars:[c],quotes:[{...t,price:0}]}),/金額/);
assert.throws(()=>P.validate({cars:[c],quotes:[{...t,price:100.5}]}),/金額/);
assert.throws(()=>P.validate({cars:[c],quotes:[{...t,date:'2026-02-31'}]}),/確認日/);
assert.throws(()=>P.validate({cars:[c],quotes:[{...t,source_url:'javascript:alert(1)'}]}),/出典URL/);
assert.throws(()=>P.validate({cars:[c],quotes:[{...t,source_url:'https://admin:password@some-car-site.example/foo'}]}),/出典URL/);
assert.equal(P.linkValid(''),'');
assert.equal(P.SOURCES.length>=3,true);
assert.ok(P.SOURCES.every(s=>s.url.startsWith('https://')));
assert.equal(P.KEY,'md-market-consumer-price-v1');
console.log('PASS personal car: separate price markets, back up, additive restore, forbidden URL rejection and original-data isolation');
