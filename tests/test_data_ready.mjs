import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import {dirname,join} from "node:path";
import {validateImport,priceEvidence,buyCap,inventoryEvidence,readiness} from "../lab/data-ready/core.mjs";
const dir=dirname(fileURLToPath(import.meta.url));
const source=JSON.parse(readFileSync(join(dir,"../lab/data-ready/sample-data.json"),"utf8"));
const docs=Object.fromEntries(source.datasets.map(x=>[x.dataset,x]));
for(const d of source.datasets) assert.equal(validateImport(d,{allowSynthetic:true}).ok,true);
assert.equal(validateImport(docs.market).ok,false,"synthetic must be rejected from user import");
assert.equal(validateImport({dataset:"market",records:[docs.market.records[0],docs.market.records[0]]},{allowSynthetic:true}).ok,false);
assert.equal(validateImport({dataset:"market",records:[{...docs.market.records[0],market_type:"retail_listing",price_jpy:-1}]},{allowSynthetic:true}).ok,false);
const q={maker:"日産",model:"ノート",grade:"X",year:2022,mileage_km:30000};
const p=priceEvidence(docs.market.records,q);
assert.equal(p.status,"descriptive_only");
assert.equal(p.count,8,"auction closes and listings must never be pooled with retail sales");
assert.equal(p.median_jpy,1365000);
assert.equal(priceEvidence(docs.market.records,{...q,grade:"S"}).status,"insufficient");
assert.equal(priceEvidence(docs.market.records,{...q,mileage_km:180000}).status,"insufficient");
const cap=buyCap({expectedSalePrice:1350000,auctionFee:40000,transport:30000,repair:50000,sellingCost:80000,holdingCost:15000,reserve:30000,targetProfit:150000});
assert.equal(cap.cap_jpy,955000);
assert.equal(buyCap({expectedSalePrice:10000,repair:15000}).feasible,false);
assert.equal(buyCap({expectedSalePrice:10000,targetProfit:-1}).status,"invalid");
const d=inventoryEvidence(docs.inventory.records,docs.demand.records,"日産","ノート","愛知県");
assert.equal(d.stock,2);assert.equal(d.inquiries,12);assert.equal(d.sold,4);
assert.equal(inventoryEvidence(docs.inventory.records,docs.demand.records,"日産","ノート","大阪府").status,"no_demand_data");
const s=readiness({market:docs.market.records,inventory:docs.inventory.records,demand:docs.demand.records});
assert.equal(s.retailClosed,8);assert.equal(s.auctionClosed,2);
assert.equal(s.auctionModelReady,false);
console.log("Data-ready lab: 15+ assertions passed");
