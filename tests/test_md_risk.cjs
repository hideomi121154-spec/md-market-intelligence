'use strict';
const assert=require('node:assert/strict');
const V=require('../valuation.js');
const R=require('../md-risk.js');
const p={...V.DEFAULTS};
const risk={...R.DEFAULT_RISK};
const base=V.calculateValues(p);
const samples=R.evaluatePeriods(p,risk,V.calculateValues);
assert.deepEqual(samples.map(x=>x.day),[30,60,90]);
assert.equal(samples[0].additionalCost,9000);
assert.equal(samples[0].addedMarkdownRate,1.5);
assert.equal(samples[0].revenue,2300000*(1-.05-.015));
assert.equal(samples[0].maxBidForTarget,1451500);
assert.equal(samples[0].profitAtBid,241500);
assert.equal(samples[0].profitGap,1500);
assert.equal(samples[0].withinArithmeticCeiling,true);
assert.equal(samples[1].withinArithmeticCeiling,false);
assert.equal(samples[2].profitAtBid<samples[1].profitAtBid,true);
assert.equal(R.maxDaysAtTarget(p,risk,V.calculateValues),31);
assert.equal(V.calculateValues(p).costs,base.costs,'pure risk calculation must not modify valuation base');
assert.equal(p.holding,V.DEFAULTS.holding,'fixed holding fee must not change');
const zero=R.evaluate(p,{dailyCost:0,monthlyMarkdown:0},90,V.calculateValues);
assert.equal(zero.additionalCost,0);
assert.equal(zero.revenue,base.conservativeRevenue);
assert.equal(zero.maxBidForTarget,base.conservativeCeiling);
assert.equal(R.maxDaysAtTarget(p,{dailyCost:0,monthlyMarkdown:0},V.calculateValues),null);
const overpriced=R.evaluate({...p,bid:2800000},risk,30,V.calculateValues);
assert.ok(overpriced.profitAtBid<0);
assert.equal(overpriced.withinArithmeticCeiling,false);
assert.equal(R.maxDaysAtTarget({...p,bid:2800000},risk,V.calculateValues),0);
const highCosts=R.evaluate({...p,holding:p.holding+20000},risk,30,V.calculateValues);
assert.equal(highCosts.maxBidForTarget,samples[0].maxBidForTarget-20000);
assert.equal(highCosts.additionalCost,samples[0].additionalCost,'flat holding fee not counted twice');
assert.throws(()=>R.evaluate(p,{dailyCost:'',monthlyMarkdown:1},30,V.calculateValues),/追加在庫費/);
assert.throws(()=>R.evaluate(p,{dailyCost:-1,monthlyMarkdown:1},30,V.calculateValues),/追加在庫費/);
assert.throws(()=>R.evaluate(p,{dailyCost:0,monthlyMarkdown:6},30,V.calculateValues),/値下がり率/);
assert.throws(()=>R.evaluate(p,risk,181,V.calculateValues),/在庫日数/);
assert.throws(()=>R.evaluate(p,risk,1.5,V.calculateValues),/整数/);
assert.throws(()=>R.evaluate(p,risk,30,null),/計算処理/);
assert.throws(()=>R.evaluate({...p,retail:0},risk,30,V.calculateValues),/想定販売価格/);
assert.throws(()=>R.evaluate({...p,downside:55},risk,30,V.calculateValues),/0〜50%/);
assert.equal(R.evaluate(p,risk,0,V.calculateValues).maxBidForTarget,base.conservativeCeiling);
console.log('PASS MD risk: 30/60/90 days, double-charge guard, no auto forecast, exact ceilings, invalid inputs');
