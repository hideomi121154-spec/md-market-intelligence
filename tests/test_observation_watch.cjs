'use strict';
const assert=require('node:assert/strict');
global.MDInventory=require('../inventory-observations.js');
const W=require('../observation-watch.js');
const base={date:'2026-10-01',make:'日産',model:'デイズ',region:'愛知県',grade:'X',color:'赤',conditions:'2022-24/距離制限',source_url:'https://www.carsensor.net/used/search?days=1',count:1200};
const later={...base,date:'2026-10-30',count:1450};
const ranking={snapshots:[{month:'2026-09',scope:'national',platform:'goonet',source_url:'https://www.goo-net.com/ranking/',models:[{rank:8,make:'日産',model:'デイズ'}]}]};
const call=(rows=[base,later],rank=ranking,date='2026-10-31')=>W.assess(rows,rank,date);
assert.equal(W.carsensorUrl(base.source_url),true);
assert.equal(W.carsensorUrl('https://carsensor.net/used'),true);
assert.equal(W.carsensorUrl('https://evilcarsensor.net/used'),false);
assert.equal(W.carsensorUrl('https://carsensor.net.evil.org/used'),false);
assert.equal(W.outageOverlap('2026-10-01','2026-10-30',base.source_url),true);
assert.equal(W.outageOverlap('2026-10-01','2026-10-16',base.source_url),false);
assert.equal(W.outageOverlap('2026-10-23','2026-10-30',base.source_url),false);
const interrupted=call()[0];
assert.equal(interrupted.status,'停止期間をまたぐ比較不可');
assert.equal(interrupted.interrupted,true);
assert.equal(interrupted.delta,null,'outage must quarantine stock change even though count exists');
assert.equal(interrupted.isComparable,false);
assert.equal(interrupted.count,1450,'original recorded value must still be displayed');
assert.equal(interrupted.demand[0].rank,8,'national interest indicator stays separate');
assert.equal(interrupted.demand[0].platform,'goonet');
const goo=call([{...base,source_url:'https://www.goo-net.com/used/abc'},{...later,source_url:'https://www.goo-net.com/used/abc'}])[0];
assert.equal(goo.status,'比較可能');
assert.equal(goo.delta,250);
assert.ok(Math.abs(goo.percent-20.8333333)<.001);
assert.equal(goo.gap,29);
assert.equal(goo.isComparable,true);
const after=call([{...base,date:'2026-10-23'},{...later,date:'2026-10-30'}])[0];
assert.equal(after.status,'掲載更新の再確認');
assert.equal(after.delta,250,'post restart is an observation but still needs confirmation');
assert.equal(after.isComparable,false);
const earlier=call([{...base,date:'2026-09-01'},{...later,date:'2026-09-15'}])[0];
assert.equal(earlier.status,'再観測が必要','stale data must take priority');
const justOne=call([later])[0];
assert.equal(justOne.status,'追加観測待ち');
assert.equal(justOne.delta,null);
const twoSources=call([base,{...later,source_url:'https://www.goo-net.com/used/abc'}]);
assert.equal(twoSources.length,2,'do not mix different sources');
assert.equal(twoSources.every(x=>x.delta===null),true);
const splitRegions=call([base,{...later,region:'全国'}]);
assert.equal(splitRegions.length,2,'do not mix regions');
const longGap=call([{...base,date:'2026-08-01',source_url:'https://www.goo-net.com/used/abc'},{...later,source_url:'https://www.goo-net.com/used/abc'}])[0];
assert.equal(longGap.status,'再観測が必要');
assert.equal(longGap.delta,null);
const noRanks=call([later],ranking,'2027-02-01')[0];
assert.deepEqual(noRanks.demand,[],'stale monthly demand must not be treated as current');
assert.equal(call([]).length,0);
assert.throws(()=>call([{...base,count:-2}]),/掲載台数/);
assert.throws(()=>call([base],ranking,'2026-13-01'),/確認日/);
assert.ok(W.ALTERNATIVES.every(s=>s.url.startsWith('https://')));
console.log('PASS source outage quarantine, source/region separation, demand freshness, invalid record safety');
