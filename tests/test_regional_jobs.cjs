'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const {validate,summarize,MACRO,PREF}=require('../regional-jobs.js');
const data=JSON.parse(fs.readFileSync(path.join(root,'data/regional_job_ads.json'),'utf8'));
assert.equal(data.month,'2026-09');
assert.equal(data.published_on,'2026-10-23');
assert.equal(data.geography_level,'six_macroregions');
assert.equal(MACRO.length,6);assert.equal(PREF.length,47);
assert.equal(validate(data),data);
let s=summarize(data,'mom');
assert.equal(s.rising,6);
assert.equal(s.falling,0);
assert.equal(s.unchanged,0);
assert.equal(s.leader.name,'北海道・東北');
assert.equal(s.leader.value,8.8);
s=summarize(data,'yoy');
assert.equal(s.leader.name,'中四国');
assert.equal(s.leader.value,62.4);
assert.equal(s.laggard.name,'関東・甲信越');
const mixed=JSON.parse(JSON.stringify(data));
mixed.regions[0].mom_pct=-2.5;
mixed.regions[1].mom_pct=0;
s=summarize(mixed,'mom');
assert.equal(s.falling,1);
assert.equal(s.unchanged,1);
assert.equal(s.rising,4);
assert.equal(s.laggard.name,'北海道・東北');
assert.throws(()=>validate({...data,source_url:'https://unknown.test'}),/形式/);
assert.throws(()=>validate({...data,regions:data.regions.slice(0,5)}),/地域数/);
assert.throws(()=>validate({...data,regions:[...data.regions.slice(0,5),data.regions[0]]}),/重複|不正/);
assert.throws(()=>validate({...data,regions:data.regions.map(r=>({...r,mom_pct:NaN}))}),/不正/);
assert.throws(()=>validate({...data,regions:data.regions.map(r=>({...r,name:'都内A市'}))}),/不正/);
const prefData={...data,geography_level:'prefectures',regions:PREF.map(name=>({name,mom_pct:1,yoy_pct:3}))};
assert.equal(summarize(prefData,'yoy').rows.length,47);
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
for(const asset of ['regional-jobs.js?v=3.0.0','regional-jobs.css?v=3.0.0']){
  assert.ok(html.includes(asset),'HTML missing '+asset);
  assert.ok(sw.includes(asset),'offline missing '+asset);
}
assert.ok(sw.includes('./data/regional_job_ads.json'));
assert.ok(html.includes('id="regional-jobs-panel"'));
assert.ok(html.includes('求人広告の増減を中古車需要や仕入れ推奨に自動換算しません'));
assert.ok(fs.readFileSync(path.join(root,'regional-jobs.js'),'utf8').includes('MDOffline.read('));
assert.ok(!fs.readFileSync(path.join(root,'regional-jobs.js'),'utf8').includes('https://www.indeed.com/'));
console.log('PASS regional job ad metadata, growth/decline sorting, missing regions, prefecture-ready schema, PWA offline linkage');
