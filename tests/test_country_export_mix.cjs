'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
require('../overseas-market.js');
const M=require('../country-export-mix.js');
const snapshot=JSON.parse(fs.readFileSync(path.join(root,'data/overseas-export-snapshot.json'),'utf8'));
const countries=M.allCountries(snapshot);
assert.ok(countries.includes('ロシア')&&countries.includes('ジョージア')&&countries.includes('パキスタン'));
assert.ok(countries.length>10);
let ru=M.analyze(snapshot,'ロシア');
assert.equal(ru.ytd.units,168891);
assert.equal(ru.ytd.period,'2026-01〜2026-09');
assert.equal(ru.types.find(x=>x.id==='ordinary').units,13997);
assert.equal(ru.types.find(x=>x.id==='kei').units,2430);
assert.equal(ru.types.find(x=>x.id==='hybrid').units,null);
assert.equal(ru.types.find(x=>x.id==='ev').units,null);
const nz=M.analyze(snapshot,'ニュージーランド');
assert.equal(nz.types.find(x=>x.id==='hybrid').units,2934);
assert.equal(nz.types.find(x=>x.id==='ev').units,366);
const uk=M.analyze(snapshot,'イギリス');
assert.equal(uk.ytd,null,'top10 country YTD absence is not zero');
assert.equal(uk.types.find(x=>x.id==='hybrid').units,2249);
assert.equal(M.analyze(snapshot,'英国').country,'イギリス');
assert.equal(M.analyze(snapshot,'ロシア',[],'2026-08').types.find(x=>x.id==='ordinary').units,null);
const official='https://www.customs.go.jp/toukei/';
const row={period:'2026-09',country:'ロシア',hs_code:'8703.22-910',units:123,source_url:official};
assert.equal(M.validateRow(row).hs_code,'870322910');
assert.equal(M.validateRow({...row,units:0}).units,0,'genuine zero can be recorded if explicitly provided');
assert.throws(()=>M.validateRow({...row,hs_code:'8703.22-920'}),/未対応/);
assert.throws(()=>M.validateRow({...row,source_url:'https://not-customs.example/'}),/確認/);
assert.throws(()=>M.validateRow({...row,period:'2025-09'}),/確認/);
assert.throws(()=>M.validateRow({...row,units:-1}),/確認/);
assert.throws(()=>M.validateRow({...row,units:'abc'}),/確認/);
const parsed=M.parseCSV('period,country,hs_code,units,source_url\n2026-09,"ロシア",8703.22-910,123,'+official+'\n');
assert.equal(parsed.length,1);
assert.equal(M.analyze(snapshot,'ロシア',parsed).hsRows[0].description,'ガソリン／1,000cc超〜1,500cc');
assert.equal(M.mergeRows(parsed,parsed).length,1);
assert.throws(()=>M.mergeRows(parsed,[{...row,units:456}]),/上書きしません/);
assert.throws(()=>M.parseCSV('month,country,hs_code,units,source_url\n'),/見出し/);
assert.throws(()=>M.parseCSV('period,country,hs_code,units,source_url\n2026-09,ロシア,8703.22-910,1\n'),/列数/);
assert.equal(M.restore(M.backup(parsed)).length,1);
assert.throws(()=>M.restore('{"kind":"other","rows":[]}'),/専用/);
assert.equal(M.toCSV(parsed).includes('"870322910"'),true);
const html=fs.readFileSync(path.join(root,'index.html'),'utf8'),sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
for(const id of ['country-mix-panel','country-mix-country','country-mix-month','country-mix-type',
 'country-mix-details','country-mix-ranking','country-mix-csv','country-mix-import','country-mix-backup','country-mix-status','country-mix-template'])
 assert.ok(html.includes('id="'+id+'"'),id);
for(const asset of ['country-export-mix.js?v=4.1.0','country-export-mix.css?v=4.1.0'])
 assert.ok(html.includes(asset)&&sw.includes(asset),asset);
assert.ok(html.indexOf('overseas-market.js?v=3.8.0')<html.indexOf('country-export-mix.js?v=4.1.0'));
const src=fs.readFileSync(path.join(root,'country-export-mix.js'),'utf8');
assert.ok(!src.includes('innerHTML')&&!src.includes('localStorage.removeItem'));
console.log('PASS: country/category top-five gaps, incompatible periods, 2026 customs HS import, conflicts, backup, PWA wiring');
