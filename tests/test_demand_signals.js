'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const D=require('../demand-signals.js');
const json=JSON.parse(fs.readFileSync(__dirname+'/../data/demand_rankings.json','utf8'));
const snaps=D.validateData(json);
assert.equal(snaps.length,2);
assert.equal(snaps[0].models.length,5);
assert.equal(snaps[1].models.length,8);
const list=D.compare(snaps,'2026-09');
const find=(make,model)=>list.find(x=>D.key(x)===D.key({make,model}));
assert.equal(find('トヨタ','アルファード').carsensor.rank,3);
assert.equal(find('トヨタ','アルファード').goonet.rank,1);
assert.equal(find('トヨタ','プリウス').carsensor.rank,5);
assert.equal(find('トヨタ','プリウス').goonet.rank,2);
assert.equal(find('ダイハツ','タント').carsensor.rank,4);
assert.equal(find('ダイハツ','タント').goonet.rank,3);
assert.equal(find('ホンダ','N-BOX').goonet,null,'N-BOX Custom cannot be silently merged with N-BOX');
assert.ok(find('ホンダ','N-BOXカスタム').goonet);
assert.equal(list.filter(x=>x.carsensor&&x.goonet).length,3);
assert.equal(D.compare(snaps,'2026-08').length,0);
assert.throws(()=>D.manualEntry({month:'2026-15',platform:'goonet',rank:1,make:'ホンダ',model:'フィット'}));
assert.throws(()=>D.manualEntry({month:'2026-09',platform:'goonet',rank:0,make:'ホンダ',model:'フィット'}));
assert.throws(()=>D.validateSnapshot({...snaps[0],models:[...snaps[0].models,{...snaps[0].models[0]}]}),/重複/);
const appended=D.manualEntry({month:'2026-09',platform:'goonet',rank:9,make:'日産',model:'セレナ'});
assert.equal(D.compare(snaps,'2026-09',[appended]).filter(x=>x.carsensor&&x.goonet).length,4);
assert.equal(D.key({make:'ホンダ',model:'Ｎ－ＢＯＸ'}),D.key({make:'ホンダ',model:'N-BOX'}));
console.log('PASS: 15 independent demand rank validations and honest partial data comparison');