'use strict';
const assert=require('node:assert/strict');
const {calculateValues,DEFAULTS}=require('./valuation.js');
let r=calculateValues(DEFAULTS);
assert.equal(r.costs,450000);
assert.equal(r.baseCeiling,1610000);
assert.equal(r.conservativeCeiling,1495000);
assert.equal(r.breakEvenCeiling,1735000);
assert.equal(r.expectedProfitAtBid,285000);
assert.equal(r.profitGap,45000);
assert.equal(r.bidWithinLimit,true);
assert.equal(r.feasible,true);
r=calculateValues({...DEFAULTS,bid:1600000});
assert.equal(r.bidWithinLimit,false);
r=calculateValues({...DEFAULTS,retail:100000,profit:300000});
assert.equal(r.feasible,false);
assert.throws(()=>calculateValues({...DEFAULTS,downside:80}),/0〜50/);
assert.throws(()=>calculateValues({...DEFAULTS,retail:-1}),/0以上/);
console.log('5 independent purchase-ceiling calculation tests passed');
